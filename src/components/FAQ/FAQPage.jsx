// ─── Sub-components ──────────────────────────────────────────────────────────

function FAQItem({ question, answer }) {
  const [open, setOpen] = useState(false);

  return (
    <div
      className={`${styles.faqItem} ${open ? styles.faqItemOpen : ""}`}
      aria-expanded={open}
    >
      <button
        className={styles.summary}
        onClick={() => setOpen((v) => !v)}
        aria-expanded={open}
      >
        {question}
        <span className={`${styles.chevron} ${open ? styles.chevronOpen : ""}`} aria-hidden="true" />
      </button>
      {open && (
        <div className={styles.answer}>
          {answer}
        </div>
      )}
    </div>
  );
}

function FAQGroup({ heading, about, items }) {
  if (items.length === 0) return null;
  return (
    <section className={styles.group}>
      <h2 className={styles.groupHeading}>{heading}</h2>
      <p className={styles.groupAbout}>{about}</p>
      {items.map((item) => (
        <FAQItem key={item.q} question={item.q} answer={item.a} />
      ))}
    </section>
  );
}

// ─── Main Page ───────────────────────────────────────────────────────────────

export default function FAQPage() {
  const [search, setSearch] = useState("");
  const [activeCat, setActiveCat] = useState("all");

  const filtered = useMemo(() => {
    const term = search.trim().toLowerCase();
    return FAQ_GROUPS.map((group) => {
      const inCat = activeCat === "all" || group.cat === activeCat;
      if (!inCat) return { ...group, items: [] };
      if (!term) return group;
      const items = group.items.filter((item) => {
        const qMatch = item.q.toLowerCase().includes(term);
        // convert JSX answer to plain text for search
        const aText =
          typeof item.a === "string"
            ? item.a
            : item.a?.props
            ? JSON.stringify(item.a)
            : "";
        return qMatch || aText.toLowerCase().includes(term);
      });
      return { ...group, items };
    });
  }, [search, activeCat]);

  const totalVisible = filtered.reduce((acc, g) => acc + g.items.length, 0);

  return (
    <div className={styles.page}>
      <h1 className={styles.h1}>Frequently asked questions</h1>
      <p className={styles.lede}>
        Answers about checking text, reading your results, and how your writing
        is handled.
      </p>

      {/* Search */}
      <label className={styles.searchLabel}>
        <span className={styles.srOnly}>Search questions</span>
        <input
          type="search"
          className={styles.searchInput}
          placeholder='Search, for example "short text" or "privacy"'
          autoComplete="off"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
        />
      </label>

      {/* Filter pills */}
      <div className={styles.filters} role="group" aria-label="Filter by category">
        {CATEGORIES.map((cat) => (
          <button
            key={cat.id}
            type="button"
            className={`${styles.filterBtn} ${activeCat === cat.id ? styles.filterBtnActive : ""}`}
            aria-pressed={activeCat === cat.id}
            onClick={() => setActiveCat(cat.id)}
          >
            {cat.label}
          </button>
        ))}
      </div>

      {/* Count status */}
      <div className={styles.status} role="status" aria-live="polite">
        {totalVisible > 0
          ? `${totalVisible} ${totalVisible === 1 ? "question" : "questions"}`
          : ""}
      </div>

      {/* Groups */}
      {filtered.map((group) => (
        <FAQGroup
          key={group.cat}
          heading={group.heading}
          about={group.about}
          items={group.items}
        />
      ))}

      {/* Empty state */}
      {totalVisible === 0 && (
        <div className={styles.empty}>
          <strong>No questions match your search.</strong>
          <br />
          Try fewer words, or select <em>All</em> to see every topic.
        </div>
      )}

      {/* Footer note */}
      <div className={styles.note}>
        <strong>TagaDetect gives an estimate, not proof.</strong> Use a result
        as one signal alongside your own judgment, and give people a chance to
        explain before drawing conclusions.
      </div>
    </div>
  );
}
